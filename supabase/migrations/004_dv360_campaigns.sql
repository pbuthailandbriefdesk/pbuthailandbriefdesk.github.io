-- DV360 campaigns per advertiser, pasted by Admins from a DV360 export.
-- The app uses it to pick the DV360 Campaign ID for a brief from its advertiser.
create table if not exists public.dv360_campaigns (
  id            bigint generated by default as identity primary key,
  advertiser_id text not null,          -- DV360 advertiser ID (brands.advertiser_id)
  campaign_id   text not null unique,
  campaign_name text,
  created_at    timestamptz not null default now(),
  modified_at   timestamptz not null default now()
);
create index if not exists dv360_campaigns_adv_idx on public.dv360_campaigns (advertiser_id);

drop trigger if exists dv360_campaigns_touch on public.dv360_campaigns;
create trigger dv360_campaigns_touch before update on public.dv360_campaigns
  for each row execute function public.touch_modified_at();

-- Same open access as every other table (003_open_access.sql).
alter table public.dv360_campaigns enable row level security;
drop policy if exists "open" on public.dv360_campaigns;
create policy "open" on public.dv360_campaigns for all to anon, authenticated using (true) with check (true);
grant select, insert, update, delete on public.dv360_campaigns to anon, authenticated;
grant usage, select on sequence public.dv360_campaigns_id_seq to anon, authenticated;

notify pgrst, 'reload schema';

select count(*) as dv360_campaigns_rows from public.dv360_campaigns;
