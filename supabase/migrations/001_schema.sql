-- L'Oréal Brief Desk: schema migrated from the SharePoint lists on
-- https://insidemedia.sharepoint.com/sites/programmaticcampaignbriefth
--
-- One table per list. Column names are the Power Apps display names in snake_case
-- (SharePoint field_N columns are mapped to their real names). `id` keeps the
-- SharePoint item ID so history and sort order carry over. `sp_legacy` holds
-- SharePoint-only values the app never read (author/editor IDs, duplicate columns).
--
-- Run this once in the Supabase SQL editor, then run the files in supabase/seed/.

-- ---------------------------------------------------------------------------
-- Access helpers
-- ---------------------------------------------------------------------------

-- Only these email domains may sign in. Edit the list to add more.
create or replace function public.allowed_email(addr text)
returns boolean language sql immutable as $$
  select split_part(lower(coalesce(addr, '')), '@', 2) in ('wppmedia.com')
$$;

create or replace function public.my_email()
returns text language sql stable as $$
  select lower(coalesce(auth.jwt() ->> 'email', ''))
$$;

create or replace function public.is_wpp()
returns boolean language sql stable as $$
  select auth.role() = 'authenticated' and public.allowed_email(public.my_email())
$$;

-- Block sign-ups from other domains before an account is created.
create or replace function public.enforce_email_domain()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if not public.allowed_email(new.email) then
    raise exception 'Only @wppmedia.com email addresses can sign in to the Brief Desk';
  end if;
  return new;
end $$;

drop trigger if exists enforce_email_domain on auth.users;
create trigger enforce_email_domain
  before insert on auth.users
  for each row execute function public.enforce_email_domain();

create or replace function public.touch_modified_at()
returns trigger language plpgsql as $$
begin
  new.modified_at := now();
  return new;
end $$;

