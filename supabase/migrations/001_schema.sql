    execute format('create trigger %I_touch before update on public.%I
                    for each row execute function public.touch_modified_at()', t, t);
  end loop;
end $$;

-- ---------------------------------------------------------------------------
-- Row level security
-- ---------------------------------------------------------------------------
-- Same reach as the Power App: every signed-in desk member can read and work on
-- briefs (the screens decide who sees which button). Reference lists are
-- read-only except for Admins. Notifications are private to their recipient.

do $$
declare t text;
begin
  foreach t in array array['briefs','brief_events','brief_ios','brief_lines','brief_ad_groups','brief_ads']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy "wpp read" on public.%I for select using (public.is_wpp())', t);
    execute format('create policy "wpp insert" on public.%I for insert with check (public.is_wpp())', t);
    execute format('create policy "wpp update" on public.%I for update using (public.is_wpp()) with check (public.is_wpp())', t);
    execute format('create policy "wpp delete" on public.%I for delete using (public.is_wpp())', t);
  end loop;

  foreach t in array array['desk_team','brands','holidays','sdf_defaults']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy "wpp read" on public.%I for select using (public.is_wpp())', t);
    execute format('create policy "admin insert" on public.%I for insert with check (public.is_wpp() and public.my_role() = ''Admin'')', t);
    execute format('create policy "admin update" on public.%I for update using (public.is_wpp() and public.my_role() = ''Admin'') with check (public.is_wpp() and public.my_role() = ''Admin'')', t);
    execute format('create policy "admin delete" on public.%I for delete using (public.is_wpp() and public.my_role() = ''Admin'')', t);
  end loop;
end $$;

alter table public.notifications enable row level security;
create policy "own read" on public.notifications for select
  using (public.is_wpp() and lower(recipient_email) = public.my_email());
create policy "wpp insert" on public.notifications for insert
  with check (public.is_wpp());
create policy "own update" on public.notifications for update
  using (public.is_wpp() and lower(recipient_email) = public.my_email())
  with check (public.is_wpp() and lower(recipient_email) = public.my_email());
create policy "own delete" on public.notifications for delete
  using (public.is_wpp() and lower(recipient_email) = public.my_email());
