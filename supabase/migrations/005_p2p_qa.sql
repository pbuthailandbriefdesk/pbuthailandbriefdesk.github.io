-- P2P QA: after the Buyer sets the campaign up, a QA person compares the DV360 SDF
-- export with the brief. Status flow: In set-up → In QA → Set up (Pass) / In set-up (Fail).
alter table public.briefs
  add column if not exists qa_result            text,         -- Pass | Fail
  add column if not exists qa_requested_at      timestamptz,
  add column if not exists qa_done_at           timestamptz,
  add column if not exists qa_email             text,
  add column if not exists qa_attempts          numeric default 0,
  add column if not exists qa_passed_first_time text;          -- Yes | No

create table if not exists public.qa_runs (
  id          bigint generated by default as identity primary key,
  brief_id    text not null references public.briefs (brief_id) on update cascade on delete cascade,
  by_email    text,
  at          timestamptz not null default now(),
  decision    text,          -- READY TO LAUNCH | READY WITH REVIEW | NOT READY TO LAUNCH
  result      text,          -- Pass | Fail (what the QA person decided)
  counts      jsonb,         -- { pass, fail, review, reminder, critical, high }
  findings    jsonb,         -- every check: scope, entity, parameter, planned, actual, status, risk, reason, action
  manual      jsonb,         -- manual checks and whether they were ticked
  files       text,          -- names of the SDF files used
  note        text,
  created_at  timestamptz not null default now(),
  modified_at timestamptz not null default now()
);
create index if not exists qa_runs_brief_idx on public.qa_runs (brief_id);

alter table public.qa_runs enable row level security;
drop policy if exists "open" on public.qa_runs;
create policy "open" on public.qa_runs for all to anon, authenticated using (true) with check (true);
grant select, insert, update, delete on public.qa_runs to anon, authenticated;
grant usage, select on sequence public.qa_runs_id_seq to anon, authenticated;

notify pgrst, 'reload schema';

select column_name from information_schema.columns where table_name = 'briefs' and column_name like 'qa_%' order by 1;
